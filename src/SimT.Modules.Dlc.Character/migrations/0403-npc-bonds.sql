-- Canonical bonds; directed kinds preserve the subject in npc_a.
CREATE TABLE IF NOT EXISTS kz_npc_bond (
 npc_a INTEGER NOT NULL REFERENCES np_npc(id), npc_b INTEGER NOT NULL REFERENCES np_npc(id),
 kind TEXT NOT NULL CHECK(kind IN ('parent','lord','mentor','sworn','spouse','sibling','friend','rival')),
 strength INTEGER NOT NULL CHECK(strength BETWEEN 0 AND 100), since_date TEXT NOT NULL,
 source TEXT NOT NULL CHECK(source IN ('history','sim')), PRIMARY KEY(npc_a,npc_b,kind),
 CHECK(npc_a <> npc_b), CHECK(kind IN ('parent','lord','mentor') OR npc_a < npc_b));
CREATE INDEX IF NOT EXISTS ix_kz_bond_b ON kz_npc_bond(npc_b);
CREATE TABLE IF NOT EXISTS kz_bond_state (key TEXT PRIMARY KEY, value TEXT NOT NULL);
