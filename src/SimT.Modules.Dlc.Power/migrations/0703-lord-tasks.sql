CREATE TABLE IF NOT EXISTS po_lord_trust (
 faction_id INTEGER PRIMARY KEY, trust INTEGER NOT NULL DEFAULT 50 CHECK(trust BETWEEN 0 AND 100),
 failures INTEGER NOT NULL DEFAULT 0, notice TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS po_lord_task (
 id INTEGER PRIMARY KEY, faction_id INTEGER NOT NULL, month_key INTEGER NOT NULL UNIQUE,
 template TEXT NOT NULL, item_id INTEGER NOT NULL DEFAULT 0, quantity INTEGER NOT NULL,
 city_id INTEGER NOT NULL, target_id INTEGER NOT NULL DEFAULT 0, baseline INTEGER NOT NULL DEFAULT 0,
 assigned_day INTEGER NOT NULL, deadline_day INTEGER NOT NULL, state TEXT NOT NULL DEFAULT 'active',
 merit INTEGER NOT NULL, bonus INTEGER NOT NULL, evidence INTEGER NOT NULL DEFAULT 0,
 acknowledged INTEGER NOT NULL DEFAULT 0);
CREATE UNIQUE INDEX IF NOT EXISTS po_lord_one_active ON po_lord_task(state) WHERE state='active';
